// Standing Order through XO invitations on chipnet: fund (subscriber), claim (anyone, role "service"), last claim (anyone).
// Each step is one XO invitation created, filled, signed and executed by the XO engine; every invitation is saved to
// invitations/<n>-<action>.xo.json (serializeInvitation) for the blaze.xo.cash debug tool.
//   XO_MNEMONIC_FILE=<file> node --import ./lib/no-native.mjs invite.mjs
// The XO wallet must hold ~50,000 chipnet sats on its first address (printed at start).
import "fake-indexeddb/auto";
import fs from "node:fs";
import crypto from "node:crypto";
import { Engine, XO_SUPPORTED_NETWORKS } from "@xo-cash/engine";
import { StorageType } from "@xo-cash/state";
import { p2pkhTemplate } from "@xo-cash/templates";
import { serializeInvitation } from "@xo-cash/utils";
import { lockingBytecodeToCashAddress, hexToBin, binToHex, sha256 } from "@bitauth/libauth";
import T from "./standing-order.template.mjs";

const log = (...a) => console.log(new Date().toISOString(), ...a);
const RUN = new URL("./invitations/run.json", import.meta.url);
const run = fs.existsSync(RUN) ? JSON.parse(fs.readFileSync(RUN, "utf8")) : { orderId: binToHex(crypto.randomBytes(8)), steps: [] };
const save = () => fs.writeFileSync(RUN, JSON.stringify(run, null, 1) + "\n");
// Order terms: the repo's chipnet test merchant and subscriber (same as demo.mjs), 20,000 sats per 1-block period.
const TERMS = { merchantPkh: "", subscriberPkh: "", amountPerPeriod: 20000n, periodBlocks: 1, maxFee: 1000n, orderId: run.orderId };
TERMS.merchantPkh = process.env.MERCHANT_PKH; TERMS.subscriberPkh = process.env.SUBSCRIBER_PKH;
if (!/^[0-9a-f]{40}$/.test(TERMS.merchantPkh || "") || !/^[0-9a-f]{40}$/.test(TERMS.subscriberPkh || "")) throw new Error("set MERCHANT_PKH and SUBSCRIBER_PKH (40 hex)");
const FUND = BigInt(process.env.FUND_SATS || "45000");

const mnemonic = fs.readFileSync(process.env.XO_MNEMONIC_FILE, "utf8").trim();
const e = await Engine.create(mnemonic, { network: XO_SUPPORTED_NETWORKS.chipnet, storageType: StorageType.INDEXEDDB, databaseFilename: "XO-standing-order-run" });
const p2 = (await e.importTemplate(p2pkhTemplate)).templateIdentifier;
const so = (await e.importTemplate(T)).templateIdentifier;
await e.setDefaultPolicies({ change: { templateIdentifier: p2 }, receive: { templateIdentifier: p2 }, address: { templateIdentifier: p2 } });
const walletLock = await e.generateLockingBytecodeFromDefaultPolicy("address");
log("XO wallet address", lockingBytecodeToCashAddress({ bytecode: hexToBin(walletLock), prefix: "bchtest" }).address, "| template", so.slice(0, 12));

const termVars = (role) => Object.entries(TERMS).map(([k, v]) => ({ variableIdentifier: k, roleIdentifier: role, value: v }));
const id = (inv) => inv.invitation.invitationIdentifier;
async function finish(n, action, inv) {
  const missing = await e.listMissingRequirements(id(inv));
  log(action, "missing before execute:", JSON.stringify(missing, (k, v) => typeof v === "bigint" ? v.toString() : v).slice(0, 400));
  const own = await e.listOwnInputIndexes(id(inv));
  // Own wallet inputs are signed by the engine; the covenant input needs no key but its unlocking script is still generated by
  // signInvitation (it compiles claimUnlockingBytecode from the template).
  const idx = new Set(own); if (action !== "fund") idx.add(0);
  for (const i of idx) inv = await e.signInvitation(id(inv), i);
  if (process.env.DRY) { // print the built transaction instead of broadcasting const b = await e.buildInvitationTransactionFromMergedCommit(id(inv)); const { decodeTransactionBch } = await import("@bitauth/libauth");
    const tx = decodeTransactionBch(hexToBin(b.serializedTransaction)); console.log("DRY", JSON.stringify({ version: tx.version, locktime: tx.locktime, inputs: tx.inputs.map((i) => ({ seq: i.sequenceNumber, ulen: i.unlockingBytecode.length, u: binToHex(i.unlockingBytecode).slice(0, 24) })), outputs: tx.outputs.map((o) => ({ v: String(o.valueSatoshis), l: binToHex(o.lockingBytecode).slice(0, 50) })) })); process.exit(0); }
  let r;
  for (let attempt = 1; ; attempt++) {
    try { r = await e.executeAction(id(inv), { broadcastTransaction: true }); break; }
    catch (err) {
      const b = await e.buildInvitationTransactionFromMergedCommit(id(inv)).catch(() => null);
      const { decodeTransactionBch } = await import("@bitauth/libauth");
      const tx = b ? decodeTransactionBch(hexToBin(b.serializedTransaction)) : null;
      log(action, "broadcast refused (attempt " + attempt + "):", String(err.message).slice(0, 160), tx ? JSON.stringify({ v: tx.version, seq: tx.inputs.map((i) => i.sequenceNumber), ulen: tx.inputs.map((i) => i.unlockingBytecode.length) }) : "");
      if (attempt >= 20 || !/BIP68/.test(String(err.message) + String(err.cause))) throw err;
      await new Promise((s) => setTimeout(s, 60000));
    }
  }
  const stored = await e.getInvitation(id(inv));
  const file = `invitations/${n}-${action}.xo.json`;
  fs.writeFileSync(new URL("./" + file, import.meta.url), serializeInvitation(stored.invitation) + "\n");
  const ser = r.builtTransaction?.serializedTransaction;
  const txid = ser ? binToHex(sha256.hash(sha256.hash(hexToBin(ser))).reverse()) : String(r.transactionHash ?? r.txid);
  run.steps.push({ n, action, txid, invitation: file, invitationIdentifier: id(inv), at: new Date().toISOString() }); save();
  log(action.toUpperCase(), "executed:", txid, "| invitation saved:", file);
  return { r, txid };
}
const waitFor = async (what, fn, everyMs = 30000, maxMs = 3600000) => { const t = Date.now(); for (;;) { const v = await fn(); if (v) return v; if (Date.now() - t > maxMs) throw new Error("timeout: " + what); await new Promise((s) => setTimeout(s, everyMs)); } };

// The order's own locking bytecode, from the template via the engine's compiler, to find its coin.
const { compile } = await import("./lib/compiler.mjs");
const { bigIntToVmNumber } = await import("@bitauth/libauth");
const num = (x) => bigIntToVmNumber(BigInt(x));
const orderLock = binToHex(compile("standingOrderLockingBytecode", { bytecode: { merchantPkh: hexToBin(TERMS.merchantPkh), subscriberPkh: hexToBin(TERMS.subscriberPkh),
  amountPerPeriod: num(TERMS.amountPerPeriod), periodBlocks: num(TERMS.periodBlocks), maxFee: num(TERMS.maxFee), orderId: hexToBin(TERMS.orderId) } }));
log("order address", lockingBytecodeToCashAddress({ bytecode: hexToBin(orderLock), prefix: "bchtest" }).address);
const { ElectrumClient } = await import("@electrum-cash/network");
const ec = new ElectrumClient("standing-order-xo", "1.4.1", "chipnet.imaginary.cash"); await ec.connect();
const orderCoins = async () => (await ec.request("blockchain.scripthash.listunspent", binToHex(sha256.hash(hexToBin(orderLock)).reverse()))).filter((u) => !u.token_data);
const tip = async () => (await ec.request("blockchain.headers.get_tip"))?.height;

// 1. fund (subscriber): the engine picks wallet coins, adds change, signs
if (!run.steps.find((s) => s.action === "fund")) {
  const coins = await waitFor("wallet coins", async () => { const u = await e.listSpendableUnspentOutputs({ templateIdentifier: p2 }); return u.length ? u : null; }, 15000, 900000);
  let inv = await e.createInvitation({ templateIdentifier: so, actionIdentifier: "fund", roleIdentifier: "subscriber" });
  inv = await e.appendInvitation(id(inv), { variables: [...termVars("subscriber"), { variableIdentifier: "fundSatoshis", roleIdentifier: "subscriber", value: FUND }],
    outputs: [{ outputIdentifier: "orderFunding", roleIdentifier: "subscriber" }] });
  let acc = 0n; const pick = [];
  for (const c of coins) { pick.push(c); acc += BigInt(c.valueSatoshis); if (acc >= FUND + 3000n) break; }
  inv = await e.appendInvitation(id(inv), { inputs: pick.map((c) => ({ outpointTransactionHash: hexToBin(c.outpointTransactionHash), outpointIndex: c.outpointIndex })) });
  inv = await e.addChangeToInvitation(id(inv));
  await finish(1, "fund", inv);
}
// 2. claim and 3. last claim (role "service": anyone; no key)
for (const [n, action] of [[2, "claim"], [3, "lastClaim"]]) {
  if (run.steps.find((s) => s.action === action)) continue;
  const coin = await waitFor("order coin one period old", async () => {
    const [c] = await orderCoins(); if (!c || c.height <= 0) return null;
    return (await tip()) >= c.height + TERMS.periodBlocks + 1 ? c : null; // one block of margin over BIP68 (mempool + Electrum lag)
  });
  const value = BigInt(coin.value);
  const last = value - TERMS.amountPerPeriod - TERMS.maxFee < TERMS.amountPerPeriod + TERMS.maxFee;
  const act = last ? "lastClaim" : "claim";
  let inv = await e.createInvitation({ templateIdentifier: so, actionIdentifier: act, roleIdentifier: "service" });
  // Outputs first: naming the order output with its locking bytecode lets the engine track the order's script hash, so it can
  // then accept the order coin as an input it may spend by the covenant's rules (role "service" holds no key).
  inv = await e.appendInvitation(id(inv), {
    variables: [...termVars("service"), { variableIdentifier: "orderSatoshis", roleIdentifier: "service", value }],
    outputs: last ? [{ outputIdentifier: "merchantLastPayment", roleIdentifier: "service" }]
      : [{ outputIdentifier: "merchantPayment", roleIdentifier: "service" }, { outputIdentifier: "orderChange", roleIdentifier: "service", lockingBytecode: hexToBin(orderLock) }] });
  inv = await e.appendInvitation(id(inv), {
    inputs: [{ inputIdentifier: "orderInput", roleIdentifier: "service", outpointTransactionHash: hexToBin(coin.tx_hash), outpointIndex: coin.tx_pos }] });
  await finish(n, act, inv);
  if (act === "lastClaim") break;
}
log("done", JSON.stringify(run.steps.map((s) => [s.action, s.txid])));
await ec.disconnect(true); await e.stop(); process.exit(0);
