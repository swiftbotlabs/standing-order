import fs from "node:fs";
import { binToHex, hash160 } from "@bitauth/libauth";
import { Contract, TransactionBuilder, randomUtxo } from "@solidcash/solidcash";
import { MockNetworkProvider } from "@solidcash/solidcash/network/mock";
import { placeholderPublicKey, placeholderSignature } from "@solidcash/solidcash/walletconnect";
const artifact = JSON.parse(fs.readFileSync("artifacts/solidcash/standing_order.json"));
const provider = new MockNetworkProvider();
const c = new Contract(artifact, [new Uint8Array(20).fill(1), new Uint8Array(20).fill(2), 20000n, 1n, 1000n], { provider });
const u = randomUtxo(); provider.addUtxo(c.address, u);
const b = new TransactionBuilder({ provider }).addInput(u, c.unlock.cancel(placeholderPublicKey(), placeholderSignature())).addOutput({ to: c.address, amount: 1000n });
const wc = b.generateWcTransactionObject({ broadcast: false });
const so = wc.sourceOutputs[0];
const unl = binToHex(so.unlockingBytecode ?? wc.transaction.inputs[0].unlockingBytecode);
const rs = binToHex(so.contract.redeemScript);
console.log("address type:", c.address.slice(0, 12), "| addressType:", c.addressType ?? "?");
console.log("redeemScript len", rs.length / 2, "| unlocking len", unl.length / 2);
console.log("unlocking ends with redeemScript:", unl.endsWith(rs));
console.log("locking:", binToHex(so.lockingBytecode).slice(0, 12), "...");
console.log("unlocking head:", unl.slice(0, 80));
console.log("redeem head:", rs.slice(0, 60));
